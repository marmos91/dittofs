#!/usr/bin/env python3
"""Regenerate the dependency graph in docs/internals/rfcs/rfc-index.md.

Reads every RFC's frontmatter (component, status, depends_on) and rewrites the
mermaid graph, the cycles line and the review groups between the markers.
Re-running it on an unchanged RFC set leaves the index byte-for-byte unchanged.

    python3 scripts/gen-rfc-graph.py
"""
import pathlib
import re
import sys

D = pathlib.Path(__file__).resolve().parent.parent / 'docs' / 'internals' / 'rfcs'
INDEX = D / 'rfc-index.md'
BEGIN = '<!-- begin: generated by scripts/gen-rfc-graph.py -->'
END = '<!-- end: generated by scripts/gen-rfc-graph.py -->'


STATUSES = {'planned', 'draft', 'reviewed', 'frozen', 'deferred'}


def frontmatter(path):
    text = path.read_text(encoding='utf-8')
    end = text.find('\n---\n', 4)
    if not text.startswith('---\n') or end < 0:
        sys.exit(f'{path.name}: no frontmatter')
    lines = text[4:end].split('\n')

    def field(k):
        v = [l.split(':', 1)[1].strip() for l in lines if l.startswith(k + ':')]
        if len(v) != 1 or not re.fullmatch(r'[^"\'#]+', v[0]):
            sys.exit(f'{path.name}: needs one plain unquoted {k}:')
        return v[0]

    # ponytail: depends_on is read as a block list of "[[rfc-N-name]]" items,
    # the only shape the set uses; anything else fails loudly rather than
    # dropping an edge. A real YAML parser is the upgrade if the shape varies.
    deps, i = [], next((i for i, l in enumerate(lines) if l.startswith('depends_on:')), None)
    if i is not None:
        if lines[i].strip() not in ('depends_on:', 'depends_on: []'):
            sys.exit(f'{path.name}: depends_on must be a block list or []')
        for l in lines[i + 1:]:
            if l and not l[0].isspace() and not l.startswith('-'):
                break
            m = re.fullmatch(r'\s*-\s*(["\']?)\[\[([^\]|#]+)\]\]\1\s*(#.*)?', l)
            if not m:
                sys.exit(f'{path.name}: unreadable depends_on item {l!r}')
            deps.append(m.group(2))
    status = field('status')
    if status not in STATUSES:
        sys.exit(f'{path.name}: unknown status {status!r}')
    return field('component'), status, deps


def main():
    rfcs = {}
    for p in sorted(D.glob('rfc-*.md')):
        if m := re.match(r'rfc-(0|[1-9]\d*)-', p.name):
            if int(m.group(1)) in rfcs:
                sys.exit(f'{p.name} and {rfcs[int(m.group(1))].name} share a number')
            rfcs[int(m.group(1))] = p
    stems = {p.stem: n for n, p in rfcs.items()}
    meta, edges, bad = {}, {}, []
    for n, p in sorted(rfcs.items()):
        comp, status, deps = frontmatter(p)
        meta[n] = (comp, status)
        for d in deps:
            if d not in stems:
                bad.append(f'{p.name}: depends_on names unknown RFC [[{d}]]')
        if p.stem in deps:
            bad.append(f'{p.name}: depends_on names itself')
        if deps and n and 'rfc-0-data-lifecycle' not in deps:
            bad.append(f'{p.name}: depends_on omits RFC 0, which every RFC that builds on another builds on')
        edges[n] = sorted({stems[d] for d in deps if d in stems} - {0, n})
    if bad:
        sys.exit('\n'.join(bad))

    lines = ['```mermaid', 'graph LR']
    for n in sorted(meta.keys() - {0}):
        node = f'  R{n}["{n} {meta[n][0]}"]'
        lines.append(node + (' --> ' + ' & '.join(f'R{d}' for d in edges[n]) if edges[n] else ''))
    lines += [f'  style R{n} stroke-dasharray: 5 5' for n in sorted(meta) if meta[n][1] == 'deferred']
    lines.append('```')
    pairs = [f'RFC {a} ↔ RFC {b}' for a in sorted(edges) for b in edges[a] if a < b and a in edges[b]]
    lines += ['', 'Cycles: ' + (', '.join(pairs) if pairs else 'none') + '.']
    # ponytail: reachability from every node, O(n·e); fine for a few dozen RFCs.
    reach = {}
    for a in edges:
        seen, todo = set(), [a]
        while todo:
            for b in edges[todo.pop()]:
                if b not in seen:
                    seen.add(b)
                    todo.append(b)
        reach[a] = seen
    groups = sorted({tuple(sorted(b for b in reach[a] if a in reach[b])) for a in edges if a in reach[a]})
    for g in groups:
        lines += ['', 'Reviewed together: ' + ', '.join(f'RFC {n}' for n in g) + '.']

    text = INDEX.read_text(encoding='utf-8')
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        sys.exit(f'{INDEX.name}: needs exactly one {BEGIN!r} and one {END!r}')
    if text.index(BEGIN) > text.index(END):
        sys.exit(f'{INDEX.name}: end marker before begin marker')
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    new = head + BEGIN + '\n' + '\n'.join(lines) + '\n' + END + tail
    if new != text:
        INDEX.write_text(new, encoding='utf-8')


if __name__ == '__main__':
    main()
